def default_data_dir() -> Path:
    """Where `toolchain-tool init` installs catalog/, docker/ and profiles/ by
    default: $XDG_DATA_HOME/toolchain-tool, or ~/.local/share/toolchain-tool."""
    base = os.environ.get("XDG_DATA_HOME") or str(Path.home() / ".local" / "share")
    return Path(base) / "toolchain-tool"


@dataclass
class Paths:
    root: Path

    @property
    def catalog(self) -> Path:
        return self.root / "catalog"

    @property
    def docker(self) -> Path:
        return self.root / "docker"

    @property
    def profiles(self) -> Path:
        return self.root / "profiles"

    @staticmethod
    def find(explicit: str | None = None) -> "Paths":
        """--root, then $TOOLCHAINS_ROOT, the current directory, the directory
        `toolchain-tool init` installs to, then the source checkout (dev installs)."""
        candidates = [explicit, os.environ.get("TOOLCHAINS_ROOT"), os.getcwd(),
                      str(default_data_dir()), str(Path(__file__).resolve().parents[2])]
        for c in candidates:
            if c and (Path(c) / "catalog" / "gcc.json").is_file():
                return Paths(Path(c).resolve())
        raise CatalogError(
            "cannot find the project directory (one with catalog/gcc.json); "
            "use --root, set $TOOLCHAINS_ROOT, or run 'toolchain-tool init' once from a checkout"
        )


class Project:
    """Catalogs and profiles on disk."""

    TOOLCHAINS = ("gcc", "llvm")

    def __init__(self, paths: Paths) -> None:
        self.paths = paths
        self.ubuntu: UbuntuCatalog | None = None
        self.catalogs: dict[str, Catalog] = {}
        self.error: str | None = None
        self.reload()

    def reload(self) -> None:
        try:
            self.ubuntu = load_ubuntu(self.paths.catalog / "ubuntu.json")
            self.catalogs = {t: load_catalog(self.paths.catalog / f"{t}.json") for t in self.TOOLCHAINS}
            self.error = None
        except CatalogError as e:
            self.catalogs, self.error = {}, str(e)

    def new_config(self, toolchain: str) -> BuildConfig:
        assert self.ubuntu is not None
        return BuildConfig(self.catalogs[toolchain], self.ubuntu)

    def profiles(self) -> list[Path]:
        return sorted(self.paths.profiles.glob("*.json")) if self.paths.profiles.is_dir() else []

    def load_profile(self, path: Path) -> tuple[BuildConfig, list[str]]:
        data = json.loads(path.read_text(encoding="utf-8"))
        toolchain = data.get("toolchain")
        if toolchain not in self.catalogs:
            raise ValueError(f"{path.name}: unknown toolchain '{toolchain}'")
        cfg = self.new_config(toolchain)
        return cfg, cfg.apply_profile(data)

    def save_profile(self, cfg: BuildConfig, name: str) -> Path:
        self.paths.profiles.mkdir(parents=True, exist_ok=True)
        path = self.paths.profiles / f"{safe_name(name)}.json"
        path.write_text(json.dumps(cfg.to_profile(), indent=2) + "\n", encoding="utf-8")
        return path


def safe_name(name: str) -> str:
    """A file-name-safe version of a profile name."""
    name = re.sub(r"[^A-Za-z0-9._-]+", "-", name.strip()).strip("-.")
    return name or "profile"


def write_script(path: Path, cfg: BuildConfig, root: Path, export_dir: str | None = None) -> None:
    """A shell script that runs the docker build from the project root."""
    rel = os.path.relpath(root, path.parent)
    body = cfg.shell_command(Path("docker"), export_dir)
    text = (
        "#!/bin/sh\n"
        f"# {cfg.catalog.title} {cfg.version} on Ubuntu {cfg.ubuntu}. Generated by toolchain-tool.\n"
        "set -e\n"
        f'cd "$(dirname "$0")/{rel}"\n'
        f"{body}\n"
    )
    path.write_text(text, encoding="utf-8")
    path.chmod(0o755)


