    def pick_ubuntu(self) -> None:
        cfg = self.cfg
        versions = cfg.ubuntu_catalog.versions
        items = [PickItem(u.label, f"gcc {u.host.get('gcc', '?')} · cmake {u.host.get('cmake', '?')}",
                          f"Released {u.released}. Host tools: " + ", ".join(f"{k} {v}" for k, v in u.host.items()))
                 for u in versions]
        current = next((i for i, u in enumerate(versions) if u.version == cfg.ubuntu), None)
        idx = pick(self.win, self.theme, "Ubuntu version", items, current,
                   intro="The base image. Versions come from catalog/ubuntu.json.", redraw=self.draw)
        if idx is not None:
            cfg.ubuntu = versions[idx].version

    def pick_version(self) -> None:
        cfg, cat = self.cfg, self.cfg.catalog
        main = cat.title.split(" ")[0]
        items: list[PickItem] = []
        values: list[str | None] = []
        for line in cat.versions:
            items.append(PickItem(f"{main} {line.major}", heading=True))
            values.append(None)
            for i, r in enumerate(line.releases):
                hint = "latest" if i == 0 else ""
                desc = f"{main} {line.major} series, first released {line.released}."
                if cat.companion and line.companion:
                    desc += f" {cat.companion.title} {line.companion.get('recommended')} recommended."
                items.append(PickItem(r, hint, desc))
                values.append(r)
        current = values.index(cfg.version) if cfg.version in values else None
        idx = pick(self.win, self.theme, f"{main} version", items, current, redraw=self.draw)
        if idx is not None and values[idx]:
            before = cfg.companion_version
            cfg.set_version(values[idx])
            if cat.companion and cfg.companion_version != before:
                self.set_message(f"{cat.companion.title} set to {cfg.companion_version} to match {main} {cfg.version}", "info")

    def pick_companion(self) -> None:
        cfg, comp = self.cfg, self.cfg.catalog.companion
        assert comp is not None
        rec = cfg.recommended_companion()
        choices = cfg.companion_choices()
        items = [PickItem(r, "recommended" if r == rec else "", f"{comp.title} {r}") for r in choices]
        current = choices.index(cfg.companion_version) if cfg.companion_version in choices else None
        line = cfg.version_line()
        idx = pick(self.win, self.theme, f"{comp.title} version", items, current,
                   intro=f"Only releases compatible with {cfg.catalog.title.split(' ')[0]} {line.major if line else cfg.version} are listed.",
                   redraw=self.draw)
        if idx is not None:
            cfg.companion_version = choices[idx]

    def edit_prefix(self) -> None:
        text = prompt_text(self.win, self.theme, "Install prefix", self.cfg.prefix,
                           "Absolute path inside the image, e.g. /opt/gcc-16 or /usr/local.", redraw=self.draw)
        if text is not None:
            text = text.strip() or self.cfg.catalog.prefix
            if not text.startswith("/"):
                self.set_message("The prefix must be an absolute path", "error")
                return
            self.cfg.prefix = text.rstrip("/") or "/"

    def edit_tag(self) -> None:
        text = prompt_text(self.win, self.theme, "Image tag", self.cfg.custom_tag or "",
                           f"Empty means automatic: {self.cfg.default_tag()}", redraw=self.draw)
        if text is not None:
            self.cfg.custom_tag = text.strip() or None

    def open_section(self, section: Section) -> None:
        if len(section.options) == 1 and section.options[0].type == "multi":
            self.app.push(MultiScreen(self.app, self.cfg, section.options[0]))
        else:
            self.app.push(SectionScreen(self.app, self.cfg, section))

    def review(self) -> None:
        self.app.push(ReviewScreen(self.app, self))

    def save(self) -> None:
        name = prompt_text(self.win, self.theme, "Save profile", self.profile or self.default_profile_name(),
                           "Saved as profiles/<name>.json.", redraw=self.draw)
        if not name or not name.strip():
            return
        name = safe_name(name)
        path = self.project.paths.profiles / f"{name}.json"
        if path.exists() and name != self.profile and not confirm(
                self.win, self.theme, "Overwrite?", [f"{path.name} already exists. Replace it?"],
                yes="Replace", no="Cancel", redraw=self.draw):
            return
        try:
            path = self.project.save_profile(self.cfg, name)
        except OSError as e:
            self.set_message(f"Cannot save: {e}", "error")
            return
        self.profile = name
        self.saved = json.dumps(self.cfg.to_profile(), sort_keys=True)
        self.set_message(f"Saved {path.relative_to(self.project.paths.root)}", "ok")


