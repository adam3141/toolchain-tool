def option_value_text(cfg: BuildConfig, opt: Option) -> str:
    value = cfg.values.get(opt.id)
    if opt.type == "bool":
        return cfg.preview(opt).split(": ", 1)[-1] if cfg.effective(opt) is not None else ""
    if opt.type == "choice":
        c = opt.choice(value)
        return c.label if c else f"{value} (invalid)"
    if opt.type == "multi":
        labels = [opt.choice(v).label for v in (cfg.effective(opt) or []) if opt.choice(v)]
        return ", ".join(labels) or "(none)"
    return value if value else "(empty)"


class SectionScreen(MenuScreen):
    def __init__(self, app: App, cfg: BuildConfig, section: Section) -> None:
        super().__init__(app)
        self.cfg = cfg
        self.section = section
        self.crumb = section.title

    def subtitle(self) -> str:
        return self.section.description

    def right(self) -> str:
        n = self.cfg.changed_count(self.section.options)
        return f"{n} changed" if n else ""

    def help(self) -> list[tuple[str, str]]:
        return [("Enter/Space", "Change"), ("d", "Default"), ("q", "Back")]

    def rows(self) -> list[Row]:
        cfg, g = self.cfg, self.theme.glyphs
        rows = []
        for opt in self.section.options:
            reason = cfg.option_reason(opt)
            stage = cfg.stage_of(opt)
            preview = cfg.preview(opt)
            detail = f"{g.arrow} {preview}" if preview else f"{g.arrow} (adds nothing)"
            if stage:
                detail += f"   [layer: {stage.title}]"
            rows.append(Row(
                opt.label,
                option_value_text(cfg, opt),
                kind="check" if opt.type == "bool" else "item",
                checked=bool(cfg.values.get(opt.id)) if opt.type == "bool" else False,
                disabled=reason,
                changed=not cfg.is_default(opt),
                status=opt.description,
                detail=detail if not reason else "",
                value_attr=self.theme.dim if opt.type == "bool" else None,
                action=lambda o=opt: self.change(o),
                reset=lambda o=opt: cfg.reset(o),
            ))
        return rows

    def change(self, opt: Option) -> None:
        cfg = self.cfg
        if opt.type == "bool":
            cfg.set(opt, not cfg.values.get(opt.id))
        elif opt.type == "choice":
            items = [PickItem(c.label, c.value if c.value != c.label else "", c.description,
                              disabled=cfg.choice_reason(opt, c)) for c in opt.choices]
            current = next((i for i, c in enumerate(opt.choices) if c.value == cfg.values.get(opt.id)), None)
            idx = pick(self.win, self.theme, opt.label, items, current, intro=opt.description, redraw=self.draw)
            if idx is not None:
                cfg.set(opt, opt.choices[idx].value)
        elif opt.type == "multi":
            self.app.push(MultiScreen(self.app, cfg, opt))
        else:
            text = prompt_text(self.win, self.theme, opt.label, cfg.values.get(opt.id) or "", opt.description,
                               redraw=self.draw)
            if text is not None:
                cfg.set(opt, text.strip())


class MultiScreen(MenuScreen):
    def __init__(self, app: App, cfg: BuildConfig, option: Option) -> None:
        super().__init__(app)
        self.cfg = cfg
        self.option = option
        self.crumb = option.label

    def subtitle(self) -> str:
        return self.option.description

    def right(self) -> str:
        return f"{len(self.cfg.effective(self.option) or [])} selected"

    def help(self) -> list[tuple[str, str]]:
        return [("Space", "Toggle"), ("d", "Defaults"), ("q", "Back")]

    def rows(self) -> list[Row]:
        cfg, opt = self.cfg, self.option
        selected = cfg.values.get(opt.id) or []
        rows = []
        for c in opt.choices:
            reason = cfg.choice_reason(opt, c)
            extra = []
            if c.requires:
                extra.append("needs " + ", ".join(opt.choice(r).label if opt.choice(r) else r for r in c.requires))
            if c.required:
                extra.append("always built")
            if c.exclusive:
                extra.append("replaces the other selections")
            rows.append(Row(
                c.label,
                "; ".join(extra),
                kind="check",
                checked=c.value in selected and reason is None,
                disabled=reason,
                changed=(c.value in selected) != (c.value in (opt.default or [])),
                status=c.description,
                detail=f"{self.theme.glyphs.arrow} {cfg.preview(opt)}",
                value_attr=self.theme.dim,
                action=lambda v=c.value: self.toggle(v),
                reset=lambda: cfg.reset(opt),
            ))
        return rows

    def toggle(self, value: str) -> None:
        notes = self.cfg.toggle_choice(self.option, value)
        if notes:
            self.set_message("; ".join(notes), "info")


