class App:
    def __init__(self, stdscr, project: Project) -> None:
        self.stdscr = stdscr
        self.project = project
        self.theme = Theme()
        self.screens: list[Screen] = []

    def push(self, screen: "Screen") -> None:
        self.screens.append(screen)

    def pop(self) -> None:
        self.screens.pop()

    def breadcrumb(self) -> str:
        return self.theme.glyphs.crumb.join(s.crumb for s in self.screens)

    def run(self) -> None:
        try:
            curses.curs_set(0)
        except curses.error:
            pass
        self.stdscr.keypad(True)
        self.push(HomeScreen(self))
        while self.screens:
            screen = self.screens[-1]
            screen.draw()
            self.stdscr.refresh()
            key = self.stdscr.getch()
            if key == curses.KEY_RESIZE:
                continue
            screen.message = None
            screen.handle_key(key)

    def run_external(self, cmd: Sequence[str], title: str) -> int:
        """Leave curses, run a command in the terminal, wait for Enter, come back."""
        curses.def_prog_mode()
        curses.endwin()
        print(f"\n\033[1m==> {title}\033[0m\n$ {' '.join(cmd[:6])} ...\n", flush=True)
        try:
            code = subprocess.call(list(cmd), cwd=self.project.paths.root)
        except (OSError, KeyboardInterrupt) as e:
            print(f"\n{e}")
            code = 130 if isinstance(e, KeyboardInterrupt) else 127
        state = "\033[32mfinished\033[0m" if code == 0 else f"\033[31mfailed (exit {code})\033[0m"
        try:
            input(f"\n==> {title} {state}. Press Enter to return to the menu. ")
        except (EOFError, KeyboardInterrupt):
            pass
        curses.reset_prog_mode()
        self.stdscr.clear()
        self.stdscr.refresh()
        return code


class Screen:
    crumb = ""

    def __init__(self, app: App) -> None:
        self.app = app
        self.message: tuple[str, str] | None = None  # (text, level), cleared on next key
        self.busy: str | None = None

    @property
    def theme(self) -> Theme:
        return self.app.theme

    @property
    def win(self):
        return self.app.stdscr

    @property
    def project(self) -> Project:
        return self.app.project

    def set_message(self, text: str, level: str = "info") -> None:
        self.message = (text, level)

    def run_busy(self, text: str, fn: Callable):
        self.busy = text
        self.draw()
        self.win.refresh()
        try:
            return fn()
        finally:
            self.busy = None

    def draw_frame(self, right: str = "", subtitle: str = "") -> tuple[int, int] | None:
        """Border, title, subtitle and dividers. Returns (h, w) or None if too small."""
        win, t, g = self.win, self.theme, self.theme.glyphs
        win.erase()
        h, w = win.getmaxyx()
        if h < MIN_H or w < MIN_W:
            put(win, 0, 0, truncate(f"Terminal too small ({w}x{h}, need {MIN_W}x{MIN_H})", w), t.warn)
            return None
        draw_box(win, 0, 0, h, w, t.border, g)
        right = f" {right} " if right else ""
        title = f" {truncate(self.app.breadcrumb(), w - 8 - len(right))} "
        put(win, 0, 2, title, t.title)
        if right and 2 + len(title) + len(right) < w - 2:
            put(win, 0, w - 2 - len(right), right, t.border)
        put(win, 1, 2, truncate(subtitle, w - 4), t.header)
        draw_divider(win, 2, 0, w, t.border, g)
        draw_divider(win, h - 3 - STATUS_ROWS, 0, w, t.border, g)
        return h, w

    def draw_status(self, h: int, w: int, lines: Sequence[tuple[str, int]]) -> None:
        """The status rows: busy text, else the transient message, else the given lines."""
        t, y0, avail = self.theme, h - 2 - STATUS_ROWS, w - 4
        if self.busy:
            put(self.win, y0, 2, truncate(f"{self.busy}...", avail), t.warn)
            return
        rows: list[tuple[str, int]] = []
        if self.message:
            text, level = self.message
            rows += [(part, t.level(level)) for part in wrap(text, avail)]
        for text, attr in lines:
            rows += [(part, attr) for part in wrap(text, avail)]
        for i, (text, attr) in enumerate(rows[:STATUS_ROWS]):
            last = i == STATUS_ROWS - 1 and len(rows) > STATUS_ROWS
            put(self.win, y0 + i, 2, truncate(text + (" ..." if last else ""), avail), attr)

    def draw(self) -> None:
        raise NotImplementedError

    def handle_key(self, key: int) -> None:
        raise NotImplementedError


# ---- generic menu --------------------------------------------------------


@dataclass
class Row:
    label: str
    value: str = ""
    kind: str = "item"           # item | check | heading | spacer
    checked: bool = False
    disabled: str | None = None  # reason the row cannot be used
    changed: bool = False        # differs from the default
    status: str = ""             # description for the status area
    detail: str = ""             # second status line (dim)
    action: Callable[[], None] | None = None
    reset: Callable[[], None] | None = None
    value_attr: int | None = None

    @property
    def selectable(self) -> bool:
        return self.kind in ("item", "check")


class MenuScreen(Screen):
    """A list of rows with a status area. Subclasses implement rows()."""

    back_label = "Back"

    def __init__(self, app: App) -> None:
        super().__init__(app)
        self.cursor = 0
        self.top = 0
        self.page = 10

    def rows(self) -> list[Row]:
        raise NotImplementedError

    def subtitle(self) -> str:
        return ""

    def right(self) -> str:
        return ""

    def help(self) -> list[tuple[str, str]]:
        g = self.theme.glyphs
        return [("↑↓" if g.up == "▲" else "Up/Dn", "Move"), ("Enter", "Select"), ("q", self.back_label)]

    def extra_key(self, key: int, row: Row | None) -> bool:
        """Screen-specific keys. Return True if handled."""
        return False

    def on_back(self) -> None:
        self.app.pop()

    # ---- behaviour -------------------------------------------------------
    def _selectable(self, rows: list[Row]) -> list[int]:
        return [i for i, r in enumerate(rows) if r.selectable]

    def _clamp_cursor(self, rows: list[Row]) -> None:
        sel = self._selectable(rows)
        if not sel:
            self.cursor = 0
        elif self.cursor not in sel:
            self.cursor = min(sel, key=lambda i: abs(i - self.cursor))

    def _move(self, rows: list[Row], delta: int) -> None:
        sel = self._selectable(rows)
        if not sel:
            return
        pos = sel.index(self.cursor) if self.cursor in sel else 0
        self.cursor = sel[max(0, min(len(sel) - 1, pos + delta))]

    def handle_key(self, key: int) -> None:
        rows = self.rows()
        self._clamp_cursor(rows)
        row = rows[self.cursor] if rows and rows[self.cursor].selectable else None
        if key in UP_KEYS:
            self._move(rows, -1)
        elif key in DOWN_KEYS:
            self._move(rows, 1)
        elif key == curses.KEY_PPAGE:
            self._move(rows, -self.page)
        elif key == curses.KEY_NPAGE:
            self._move(rows, self.page)
        elif key in (curses.KEY_HOME, ord("g")):
            self._move(rows, -len(rows))
        elif key in (curses.KEY_END, ord("G")):
            self._move(rows, len(rows))
        elif self.extra_key(key, row):
            pass
        elif key in KEY_ENTER or key in (ord(" "), curses.KEY_RIGHT, ord("l")):
            if row is None:
                return
            if row.disabled:
                self.set_message(f"{row.label}: {row.disabled}", "warn")
            elif row.action:
                row.action()
        elif key in (ord("d"), ord("D")) and row is not None and row.reset:
            row.reset()
            self.set_message(f"{row.label} reset to its default", "ok")
        elif key in BACK_KEYS:
            self.on_back()

    def draw(self) -> None:
        t, g, win = self.theme, self.theme.glyphs, self.win
        geo = self.draw_frame(self.right(), self.subtitle())
        if geo is None:
            return
        h, w = geo
        rows = self.rows()
        self._clamp_cursor(rows)
        inner_w = w - 2
        list_h = h - CHROME_H
        self.page = max(1, list_h - 1)

        # Scroll so the cursor is visible, showing the heading above it when possible.
        if self.cursor < self.top:
            self.top = self.cursor
            if self.top > 0 and rows[self.top - 1].kind == "heading":
                self.top -= 1
        elif self.cursor >= self.top + list_h:
            self.top = self.cursor - list_h + 1
        self.top = max(0, min(self.top, max(0, len(rows) - list_h)))

        label_w = min(max((len(r.label) for r in rows if r.selectable), default=10) + 1, max(16, inner_w // 2))
        check_w = len(g.check_on) + 1 if any(r.kind == "check" for r in rows) else 0
        for i in range(list_h):
            idx = self.top + i
            if idx >= len(rows):
                break
            self.draw_row(3 + i, rows[idx], idx == self.cursor, label_w, check_w, inner_w)
        if self.top > 0:
            put(win, 3, w - 1, g.up, t.warn)
        if self.top + list_h < len(rows):
            put(win, 3 + list_h - 1, w - 1, g.down, t.warn)

        status: list[tuple[str, int]] = []
        cur = rows[self.cursor] if rows and rows[self.cursor].selectable else None
        if cur:
            if cur.disabled:
                status.append((f"Unavailable: {cur.disabled}", t.warn))
            if cur.status:
                status.append((cur.status, t.info))
            if cur.detail:
                status.append((cur.detail, t.dim))
        self.draw_status(h, w, status)
        draw_help(win, h - 2, 2, w - 4, self.help(), t)

    def draw_row(self, y: int, row: Row, is_cursor: bool, label_w: int, check_w: int, inner_w: int) -> None:
        t, g, win = self.theme, self.theme.glyphs, self.win
        if row.kind == "spacer":
            return
        if row.kind == "heading":
            text = f" {g.bullet} {row.label} "
            put(win, y, 2, text, t.section)
            put(win, y, 2 + len(text), g.h * max(0, inner_w - len(text) - 2), t.border)
            return
        base = t.cursor if is_cursor else (t.dim if row.disabled else t.normal)
        if is_cursor:
            put(win, y, 1, " " * inner_w, base)
        put(win, y, 2, g.pointer if is_cursor else " ", base | curses.A_BOLD)
        put(win, y, 3, g.dot if row.changed else " ", base if is_cursor else t.changed)
        x = 5
        if check_w:
            if row.kind == "check":
                box = g.check_on if row.checked else g.check_off
                attr = base if is_cursor or row.disabled else (t.ok if row.checked else t.dim)
                put(win, y, x, box, attr)
            x += check_w
        put(win, y, x, fit(row.label, label_w), base | (curses.A_BOLD if row.changed and not row.disabled else 0))
        x += label_w + 1
        value = row.disabled if row.disabled and not row.value else row.value
        vattr = base if is_cursor else (t.dim if row.disabled else (row.value_attr if row.value_attr is not None else t.value))
        put(win, y, x, truncate(value, inner_w - x), vattr)


# ---- home ----------------------------------------------------------------


class HomeScreen(MenuScreen):
    crumb = "Toolchain Builder"
    back_label = "Quit"

    def subtitle(self) -> str:
        return "Build GCC and LLVM toolchains in Docker"

    def right(self) -> str:
        return str(self.project.paths.root)

    def rows(self) -> list[Row]:
        p = self.project
        rows: list[Row] = [Row("Build a toolchain", kind="heading")]
        if p.error:
            rows.append(Row("Catalog error", p.error.splitlines()[0], disabled="fix the catalog JSON (see status)",
                            status=p.error))
        for tid in p.TOOLCHAINS:
            cat = p.catalogs.get(tid)
            if cat is None:
                continue
            latest = cat.versions[0].releases[0]
            rows.append(Row(cat.title, f"latest {latest}", status=cat.description,
                            detail=f"catalog/{tid}.json {self.theme.glyphs.arrow} docker/{cat.dockerfile}",
                            action=lambda t=tid: self.app.push(ToolchainScreen(self.app, p.new_config(t)))))
        rows.append(Row("Profiles", kind="heading"))
        profiles = p.profiles()
        rows.append(Row("Load a saved profile", f"{len(profiles)} in profiles/",
                        disabled=None if profiles and not p.error else "no profiles saved yet" if not p.error else "catalog error",
                        status="Open a configuration saved earlier with 's' on a toolchain screen.",
                        action=self.load_profile))
        rows.append(Row("Maintenance", kind="heading"))
        rows.append(Row("Refresh versions from upstream", "ftp.gnu.org, GitHub",
                        status="Download the GCC, binutils and LLVM release lists and add new releases to "
                               "catalog/gcc.versions.json and catalog/llvm.versions.json.",
                        action=self.refresh))
        rows.append(Row("Reload catalogs", "catalog/*.json", status="Re-read the JSON catalogs after editing them.",
                        action=self.reload))
        rows.append(Row("Quit", action=self.app.pop))
        return rows

    def load_profile(self) -> None:
        files = self.project.profiles()
        items = []
        for f in files:
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
                hint = f"{data.get('toolchain', '?')} {data.get('version', '')} / ubuntu {data.get('ubuntu', '')}"
            except (OSError, json.JSONDecodeError):
                hint = "unreadable"
            items.append(PickItem(f.stem, hint, str(f)))
        idx = pick(self.win, self.theme, "Load profile", items, redraw=self.draw)
        if idx is None:
            return
        try:
            cfg, warnings = self.project.load_profile(files[idx])
        except (OSError, ValueError, json.JSONDecodeError) as e:
            message_box(self.win, self.theme, "Cannot load profile", [str(e)], danger=True, redraw=self.draw)
            return
        screen = ToolchainScreen(self.app, cfg, profile=files[idx].stem)
        self.app.push(screen)
        if warnings:
            screen.set_message("Profile loaded with warnings: " + "; ".join(warnings), "warn")
        else:
            screen.set_message(f"Loaded {files[idx].name}", "ok")

    def refresh(self) -> None:
        try:
            summary = self.run_busy("Fetching release lists", lambda: upstream.refresh(self.project.paths.catalog))
        except (upstream.UpstreamError, OSError, ValueError) as e:
            message_box(self.win, self.theme, "Refresh failed", [str(e)], danger=True, redraw=self.draw)
            return
        self.project.reload()
        body: list = [("Updated catalog/*.versions.json:", self.theme.ok), ""]
        body += [f" {self.theme.glyphs.dot} {line}" for line in summary]
        message_box(self.win, self.theme, "Versions refreshed", body, redraw=self.draw)

    def reload(self) -> None:
        self.project.reload()
        if self.project.error:
            self.set_message("Catalog error: " + self.project.error, "error")
        else:
            self.set_message("Catalogs reloaded", "ok")


