class ReviewScreen(Screen):
    """Scrollable summary: checks, build args per Docker layer, the command."""

    crumb = "Review & build"

    def __init__(self, app: App, parent: ToolchainScreen) -> None:
        super().__init__(app)
        self.parent = parent
        self.cfg = parent.cfg
        self.top = 0
        self.page = 10

    def lines(self, width: int) -> list[list[tuple[str, int]]]:
        t, g, cfg = self.theme, self.theme.glyphs, self.cfg
        out: list[list[tuple[str, int]]] = []

        def section(title: str) -> None:
            if out:
                out.append([])
            out.append([(f"{g.bullet} {title}", t.section)])

        def para(text: str, attr: int, indent: int = 2) -> None:
            for part in wrap(text, width - indent):
                out.append([(" " * indent + part, attr)])

        section("Checks")
        issues = cfg.validate()
        if not any(i.level in ("error", "warn") for i in issues):
            out.append([("  ✔ " if g.up == "▲" else "  ok ", t.ok), ("No problems found", t.ok)])
        mark = {"error": ("✖", "E"), "warn": ("▲", "!"), "info": ("ℹ", "i")}
        for issue in issues:
            sym = mark.get(issue.level, ("-", "-"))[0 if g.up == "▲" else 1]
            attr = {"error": t.error, "warn": t.warn}.get(issue.level, t.info)
            parts = wrap(issue.message, width - 6)
            out.append([(f"  {sym} ", attr), (parts[0], attr if issue.level == "error" else t.normal)])
            out += [[("    " + p, t.normal)] for p in parts[1:]]

        section("Build args by Docker layer (a change rebuilds from its layer down)")
        for n, (stage, args) in enumerate(cfg.args_by_stage(), 1):
            out.append([(f"  {n}. {stage.title}", t.header)])
            para(stage.description, t.dim, indent=5)
            for name, value in args:
                chunks = wrap(value or "(empty)", max(10, width - 8 - len(name)))
                out.append([(f"     {name} = ", t.label), (chunks[0], t.value if value else t.dim)])
                out += [[(" " * (8 + len(name)), 0), (c, t.value)] for c in chunks[1:]]

        section("Command")
        for line in cfg.shell_command(Path("docker")).splitlines():
            para(line, t.normal, indent=2)
        return out

    def draw(self) -> None:
        t, g, win, cfg = self.theme, self.theme.glyphs, self.win, self.cfg
        geo = self.draw_frame(cfg.image_tag, f"{cfg.catalog.title} {cfg.version}  ·  Ubuntu {cfg.ubuntu}")
        if geo is None:
            return
        h, w = geo
        body_w, body_h = w - 4, h - CHROME_H
        rows = self.lines(body_w)
        self.page = max(1, body_h - 1)
        self.top = max(0, min(self.top, len(rows) - body_h))
        for i, segments in enumerate(rows[self.top : self.top + body_h]):
            x = 2
            for text, attr in segments:
                put(win, 3 + i, x, text[: w - 2 - x], attr)
                x += len(text)
        if self.top > 0:
            put(win, 3, w - 1, g.up, t.warn)
        if self.top + body_h < len(rows):
            put(win, 3 + body_h - 1, w - 1, g.down, t.warn)
        end = min(len(rows), self.top + body_h)
        errors = cfg.has_errors()
        status = [("Fix the errors above before building." if errors else
                   "b builds the image, e exports the install prefix to a directory, w writes a build script.",
                   t.error if errors else t.info),
                  (f"lines {self.top + 1}-{end} of {len(rows)}", t.dim)]
        self.draw_status(h, w, status)
        draw_help(win, h - 2, 2, w - 4, [("b", "Build image"), ("e", "Export"), ("w", "Script"), ("s", "Save"),
                                         ("PgUp/PgDn", "Scroll"), ("q", "Back")], t)

    def handle_key(self, key: int) -> None:
        if key in UP_KEYS:
            self.top -= 1
        elif key in DOWN_KEYS:
            self.top += 1
        elif key == curses.KEY_PPAGE:
            self.top -= self.page
        elif key in (curses.KEY_NPAGE, ord(" ")):
            self.top += self.page
        elif key in (curses.KEY_HOME, ord("g")):
            self.top = 0
        elif key in (curses.KEY_END, ord("G")):
            self.top = 1 << 30  # clamped on draw
        elif key in (ord("b"), ord("B")):
            self.build()
        elif key in (ord("e"), ord("E")):
            self.export()
        elif key in (ord("w"), ord("W")):
            self.script()
        elif key in (ord("s"), ord("S")):
            self.parent.save()
            self.message = self.parent.message
        elif key in BACK_KEYS:
            self.app.pop()
        self.top = max(0, self.top)

    def _blocked(self) -> bool:
        if self.cfg.has_errors():
            errors = [i.message for i in self.cfg.validate() if i.level == "error"]
            message_box(self.win, self.theme, "Cannot build", errors, danger=True, redraw=self.draw)
            return True
        return False

    def build(self) -> None:
        if self._blocked():
            return
        cfg = self.cfg
        if not confirm(self.win, self.theme, "Build image",
                       [f"Build {cfg.image_tag}?", "",
                        ("This runs docker buildx in this terminal. A full compiler build can take a long time; "
                         "unchanged layers come from the build cache.", self.theme.dim)],
                       yes="Build", no="Cancel", redraw=self.draw):
            return
        code = self.app.run_external(cfg.docker_command(Path("docker")), f"Building {cfg.image_tag}")
        self.set_message(f"Built {cfg.image_tag}" if code == 0 else f"docker exited with {code}", "ok" if code == 0 else "error")

    def export(self) -> None:
        if self._blocked():
            return
        cfg = self.cfg
        default = f"out/{cfg.catalog.id}-{cfg.version}-ubuntu{cfg.ubuntu}"
        dest = prompt_text(self.win, self.theme, "Export to directory", default,
                           f"The install prefix ({cfg.prefix}) is written under this directory, relative to the project root.",
                           redraw=self.draw)
        if not dest or not dest.strip():
            return
        code = self.app.run_external(cfg.docker_command(Path("docker"), export_dir=dest.strip()), f"Exporting to {dest}")
        self.set_message(f"Exported to {dest}" if code == 0 else f"docker exited with {code}", "ok" if code == 0 else "error")

    def script(self) -> None:
        name = safe_name(self.parent.profile or self.parent.default_profile_name())
        text = prompt_text(self.win, self.theme, "Write build script", f"build-{name}.sh",
                           "Path relative to the project root. The script runs the same docker command.",
                           redraw=self.draw)
        if not text or not text.strip():
            return
        path = self.project.paths.root / text.strip()
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            write_script(path, self.cfg, self.project.paths.root)
        except OSError as e:
            self.set_message(f"Cannot write script: {e}", "error")
            return
        self.set_message(f"Wrote {text.strip()}", "ok")
