class ToolchainScreen(MenuScreen):
    def __init__(self, app: App, cfg: BuildConfig, profile: str | None = None) -> None:
        super().__init__(app)
        self.cfg = cfg
        self.crumb = cfg.catalog.title
        self.profile = profile
        self.saved = json.dumps(cfg.to_profile(), sort_keys=True)

    @property
    def dirty(self) -> bool:
        return json.dumps(self.cfg.to_profile(), sort_keys=True) != self.saved

    def subtitle(self) -> str:
        cfg = self.cfg
        parts = [f"Ubuntu {cfg.ubuntu}", f"{cfg.catalog.title.split(' ')[0]} {cfg.version}"]
        if cfg.catalog.companion:
            parts.append(f"{cfg.catalog.companion.title} {cfg.companion_version}")
        return "  ·  ".join(parts)

    def right(self) -> str:
        name = f"profile {self.profile}" if self.profile else "unsaved profile"
        return name + (" *" if self.dirty else "")

    def help(self) -> list[tuple[str, str]]:
        return [("Enter", "Open"), ("d", "Default"), ("r", "Review"), ("s", "Save"), ("q", "Back")]

    def rows(self) -> list[Row]:
        cfg, cat, g = self.cfg, self.cfg.catalog, self.theme.glyphs
        main = cat.title.split(" ")[0]
        ub = cfg.ubuntu_catalog.get(cfg.ubuntu)
        rows = [Row("General", kind="heading")]
        rows.append(Row("Ubuntu", ub.label if ub else cfg.ubuntu, changed=cfg.ubuntu != cfg.ubuntu_catalog.default,
                        status="Base image for the build and for the final image. Changing it rebuilds everything.",
                        detail=self._host_detail(), action=self.pick_ubuntu,
                        reset=lambda: setattr(cfg, "ubuntu", cfg.ubuntu_catalog.default)))
        line = cfg.version_line()
        rows.append(Row(f"{main} version", cfg.version + (f"   (released {line.released})" if line and line.released else ""),
                        changed=cfg.version != cat.versions[0].releases[0],
                        status=f"The {main} release to build. Newer point releases of a series are bug-fix only.",
                        action=self.pick_version, reset=lambda: cfg.set_version(cat.versions[0].releases[0])))
        if cat.companion:
            comp = cat.companion
            rec = cfg.recommended_companion()
            ok = cfg.companion_compatible(cfg.companion_version)
            note = "recommended" if cfg.companion_version == rec else ("compatible" if ok else "NOT compatible")
            rng = f"{line.companion.get('min')} to {line.companion.get('max')}" if line and line.companion else "any"
            rows.append(Row(comp.title, f"{cfg.companion_version}   ({note})", changed=cfg.companion_version != rec,
                            value_attr=None if ok else self.theme.error,
                            status=f"{comp.title} releases that work with {main} {line.major if line else ''}: {rng}. "
                                   f"The recommended one was current when {main} {line.major if line else ''} came out.",
                            action=self.pick_companion, reset=lambda: setattr(cfg, "companion_version", rec or "")))
        rows.append(Row("Install prefix", cfg.prefix, changed=cfg.prefix != cat.prefix,
                        status="Where the toolchain is installed inside the image (and the layout of an export).",
                        action=self.edit_prefix, reset=lambda: setattr(cfg, "prefix", cat.prefix)))
        rows.append(Row("Image tag", cfg.image_tag + ("" if cfg.custom_tag else "   (auto)"), changed=cfg.custom_tag is not None,
                        status="Tag for the final image. Leave empty to derive it from the versions.",
                        action=self.edit_tag, reset=lambda: setattr(cfg, "custom_tag", None)))

        rows.append(Row("Options", kind="heading"))
        for section in cat.sections:
            reason = cfg.section_reason(section)
            n = cfg.changed_count(section.options)
            first = section.options[0]
            if first.type == "multi":
                # Sections led by a list (languages, projects) show the selection.
                labels = [first.choice(v).label for v in cfg.effective(first) or [] if first.choice(v)]
                value = ", ".join(labels) or "(none)"
                others = n - (0 if cfg.is_default(first) else 1)
                if others:
                    value += f"  (+{others} changed)"
            else:
                value = f"{n} changed" if n else "defaults"
            changed = n > 0
            if reason:
                value = ""
            stage = self._section_stage(section)
            rows.append(Row(section.title, value, disabled=reason, changed=changed,
                            status=section.description,
                            detail=f"Docker layer: {stage}" if stage else "",
                            action=lambda s=section: self.open_section(s),
                            reset=lambda s=section: [cfg.reset(o) for o in s.options]))

        rows.append(Row("Build", kind="heading"))
        issues = cfg.validate()
        errors = sum(1 for i in issues if i.level == "error")
        warns = sum(1 for i in issues if i.level == "warn")
        summary = f"{errors} error(s)" if errors else f"{warns} warning(s)" if warns else f"ready {g.arrow} {cfg.image_tag}"
        rows.append(Row("Review & build", summary,
                        value_attr=self.theme.error if errors else self.theme.warn if warns else self.theme.ok,
                        status="Check the configuration, see the build args per Docker layer and the docker command, "
                               "then build the image, export the toolchain or write a build script.",
                        action=self.review))
        rows.append(Row("Save profile", f"profiles/{safe_name(self.profile or self.default_profile_name())}.json",
                        status="Save these settings so they can be loaded again or built from the command line.",
                        action=self.save))
        return rows

    def _host_detail(self) -> str:
        ub = self.cfg.ubuntu_catalog.get(self.cfg.ubuntu)
        if not ub or not ub.host:
            return ""
        return "Host tools: " + ", ".join(f"{k} {v}" for k, v in ub.host.items())

    def _section_stage(self, section: Section) -> str:
        stages = []
        for o in section.options:
            s = self.cfg.stage_of(o)
            if s and s.title not in stages:
                stages.append(s.title)
        return ", ".join(stages)

    def default_profile_name(self) -> str:
        return f"{self.cfg.catalog.id}-{self.cfg.version}-ubuntu{self.cfg.ubuntu}"

    def extra_key(self, key: int, row: Row | None) -> bool:
        if key in (ord("r"), ord("R")):
            self.review()
        elif key in (ord("s"), ord("S")):
            self.save()
        else:
            return False
        return True

    def on_back(self) -> None:
        if self.dirty and not confirm(self.win, self.theme, "Unsaved changes",
                                      ["Leave without saving this profile?"], yes="Leave", no="Stay",
                                      redraw=self.draw):
            return
        self.app.pop()

